/* Doctor Translation Review Component for VaaniDoc
Displays the English translation as the PRIMARY readable content,
with the original Indian-language text as a reference/source.
Shows verification status and allows doctor clinical review.

Follows modern VaaniDoc dashboard design.
English translation is the primary readable representation.
Original Indian-language text remains as source/reference.
Doctor remains the final clinical reviewer.
AI-generated translation is clearly labeled.
Warnings are visually obvious when verification needs review.
Does not diagnose the patient.
Does not allow AI output to silently overwrite doctor-entered information.
*/

import React, { useState } from "react";

/* DoctorReview - Doctor-side translation review component */
export default function DoctorReview({
  englishText,
  originalText,
  verificationStatus,
  warnings,
  clinicalData,
  onClinicalDataChange,
  onCopyCase,
  onRetranslate,
}) {
  const [showWarnings, setShowWarnings] = useState(false);
  const [editing, setEditing] = useState(false);

  /* Get status label and visual class */
  const getStatusInfo = () => {
    if (verificationStatus === "consistent") {
      return {
        label: "✓ No detected critical mismatch",
        className: "success",
        accent: "green",
      };
    }
    return {
      label: "⚠️ Needs review",
      className: "warning",
      accent: "red",
    };
  };

  const { label, className, accent } = getStatusInfo();

  /* Warning messages */
  const warningItems = (warnings || []).map(
    (w, i) => (
      <div key={i} className="pb-2 border-t border-gray-200 last:border-0">
        <p className="text-sm text-gray-600">{w.message}</p>
      </div>
    )
  );

  /* Handle warning toggle */
  const toggleWarnings = () => setShowWarnings(!showWarnings);

  /* Handle clinical data change */
  const handleChange = (field, value) => {
    onClinicalDataChange({
      ...clinicalData,
      [field]: value,
    });
  };

  return (
    <div className="space-y-6 max-w-2xl mx-auto">
      {/* English Patient Statement - PRIMARY content */}
      <div className="panel p-6 border-b border-gray-200">
        <h3 className="font-semibold text-gray-900 mb-4 flex items-center gap-2">
          <span className="text-lg text-gray-500">English Patient Statement</span>
          <span className="text-xs text-gray-400 ml-auto">
            {"AI-generated translation"}
          </span>
        </h3>
        <p className="text-lg text-gray-800 whitespace-pre-wrap">{englishText}</p>
        <p className="text-xs text-gray-400 mt-2">
          {"This is the English translation generated by the AI system. "}
          {"The doctor should verify clinical accuracy."}
        </p>
      </div>

      {/* Translation Status */}
      <div className={`panel p-4 border-t border-${accent}-200 ${accent}-100`}
        onClick={toggleWarnings}
        role="button"
        tabIndex={0}>
        <h3 className="font-semibold text-gray-900 mb-2 flex items-center gap-2">
          <span className="text-lg text-gray-500">Translation Status</span>
          <span className="text-xs text-gray-400 ml-auto ${accent}-600">
            {label}
          </span>
        </h3>
        {showWarnings ? (
          <div className="mt-2">
            <p className="text-sm text-gray-600">{label}</p>
            {warningItems}
          </div>
        ) : null}
        <button
          onClick={toggleWarnings}
          className="text-sm text-gray-500 hover:text-gray-400 ml-auto"
        >
          {showWarnings ? "Hide warnings" : "Show warnings"}
        </button>
      </div>

      {/* Original Patient Statement - source/reference */}
      <div className="panel p-4 border-t border-gray-200">
        <h3 className="font-semibold text-gray-900 mb-2">
          <span className="text-lg text-gray-500">Original Patient Statement</span>
          <span className="text-xs text-gray-400 ml-auto">
            {"Indian-language source"}
          </span>
        </h3>
        <p className="text-lg text-gray-800 whitespace-pre-wrap">{originalText}</p>
        <p className="text-xs text-gray-400 mt-1">
          {"Original statement in patient's native language. "}
          {"Used for reference and verification purposes."}
        </p>
      </div>

      {/* Language identifier */}
      <div className="panel p-4" style={{ borderColor: "#e5e7eb" }}>
        <h3 className="font-semibold text-gray-900 mb-2">Language</h3>
        <p className="text-sm text-gray-500">{clinicalData.bodyLocation ? "Gujarati" : "—"}</p>
        <p className="text-xs text-gray-400 mt-1">
          {"Original language code stored for reference. "}
          {"Doctor does not need to understand this language."}
        </p>
      </div>

      {/* Clinical Information form */}
      <div className="panel p-4">
        <h3 className="font-semibold text-gray-900 mb-4">Clinical Information</h3>

        {/* Chief Complaint */}
        <div>
          <label className="block text-sm text-gray-500 mb-1">
            Chief Complaint
          </label>
          <p className="text-sm text-gray-800 whitespace-pre-wrap">{clinicalData.chiefComplaint}</p>
        </div>

        {/* Symptoms */}
        <div>
          <label className="block text-sm text-gray-500 mb-1">
            Symptoms
          </label>
          <div className="grid grid-cols-2 gap-2">
            {clinicalData.symptoms.map((symptom, index) => (
              <div key={index} className="p-2 border rounded text-sm text-gray-700">
                {symptom}
              </div>
            ))}
          </div>
        </div>

        {/* Duration */}
        <div>
          <label className="block text-sm text-gray-500 mb-1">
            Duration
          </label>
          <p className="text-sm text-gray-800 whitespace-pre-wrap">{clinicalData.duration}</p>
        </div>

        {/* Severity */}
        <div>
          <label className="block text-sm text-gray-500 mb-1">
            Severity
          </label>
          <p className="text-sm text-gray-800 whitespace-pre-wrap">{clinicalData.severity}</p>
        </div>

        {/* Body Location */}
        <div>
          <label className="block text-sm text-gray-500 mb-1">
            Body Location
          </label>
          <p className="text-sm text-gray-800 whitespace-pre-wrap">{clinicalData.bodyLocation}</p>
        </div>

        {/* Associated Symptoms */}
        <div>
          <label className="block text-sm text-gray-500 mb-1">
            Associated Symptoms
          </label>
          <div className="grid grid-cols-2 gap-2">
            {clinicalData.associatedSymptoms.map((symptom, index) => (
              <div key={index} className="p-2 border rounded text-sm text-gray-700">
                {symptom}
              </div>
            ))}
          </div>
        </div>

        {/* Urgency */}
        <div>
          <label className="block text-sm text-gray-500 mb-1">
            Urgency
          </label>
          <p className="text-sm text-gray-800 whitespace-pre-wrap">{clinicalData.urgency}</p>
        </div>
      </div>

      {/* Action buttons */}
      <div className="flex justify-end space-x-3">
        {onCopyCase && (
          <button
            onClick={onCopyCase}
            className="btn btn-secondary"
          >
            Copy Case
          </button>
        )}
        {onRetranslate && (
          <button
            onClick={onRetranslate}
            className="btn btn-secondary"
          >
            Re-translate
          </button>
        )}
        <button
          onClick={() => setEditing(!editing)}
          className={editing ? "btn danger" : "btn"}
        >
          {editing ? "Save Changes" : "Edit Clinical Info"}
        </button>
      </div>
    </div>
  );
}

export { DoctorReview };